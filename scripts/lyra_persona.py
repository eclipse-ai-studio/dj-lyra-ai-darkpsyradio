def reply_user_prompt(post_text: str, post_context: str, thread_parent: str | None, comment: str) -> str:
    parts = [f"【元の自分の投稿】\n{post_text}"]
    if post_context:
        parts.append(f"【元の投稿の補足情報】\n{post_context}")
